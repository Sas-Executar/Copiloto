#!/usr/bin/env python3
"""Render a mapa_operacional projection (permanent, non-weekly Mapa-OS reading) as
print-ready A4 HTML, using the EXECUTAR design tokens and the same component
vocabulary as assets/templates/executive-report-a4.html (card, metric, callout,
pill, section-head, table). Unlike the Prisma A4 template (fixed 3-face, 100
named placeholders), this content is variable-length (N macroáreas, N domínios
each), so it is generated by looping over the payload rather than substituting
into a fixed set of placeholders.

Uso:
  python3 render_mapa_operacional.py payload.json output.html
"""
