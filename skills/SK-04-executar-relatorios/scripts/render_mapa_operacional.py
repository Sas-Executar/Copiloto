def render_cover(meta: dict, visao: dict) -> str:
    return f"""
<section class="cover">
  <div class="brand"><span class="brand-mark">E</span><span>EXECUTAR</span></div>
  <div class="cover-main">
    <div class="eyebrow">{e(meta.get('tipo_de_mapa', 'Mapa operacional'))}</div>
    <h1>{e(meta.get('titulo'))}</h1>
    <p class="dek">{e(meta.get('subtitulo'))}</p>
    <p class="obj">{e(meta.get('objetivo'))}</p>
  </div>
  <div class="cover-meta">
    <div>
      <div class="kicker">Fonte primária</div>
      <strong>{e(meta.get('fonte_principal'))}</strong>
    </div>
    <div style="text-align:right">
      <div class="kicker">Referência</div>
      <span>{e(meta.get('data_de_referencia'))}</span>
    </div>
  </div>
</section>
"""


def render_visao_geral(visao: dict) -> str:
    cards = ""
    for n in visao.get("numeros_chave", []):
        obs = f'<div class="obs">{e(n.get("observacao",""))}</div>' if n.get("observacao") else ""
        cards += f"""
    <div class="metric">
      <div class="value">{e(n['valor'])}</div>
      <div class="label">{e(n['rotulo'])}</div>
      {obs}
    </div>"""
    return f"""
<section class="report-page">
  <div class="section-head"><div class="section-no">01</div><h2>Visão geral</h2></div>
  <p class="lead">{e(visao.get('resumo'))}</p>
  <div class="grid-4" style="margin-bottom:6mm">{cards}
  </div>
</section>
"""


def render_como_ler(passos: list) -> str:
    items = ""
    for p in passos:
        items += f"""
    <div class="card soft">
      <span class="pill">Passo {e(p['passo'])}</span>
      <h3 style="margin-top:2.5mm; font-size:10.5pt">{e(p['titulo'])}</h3>
      <p style="font-size:8.6pt; color:var(--exec-color-ink-secondary)">{e(p['descricao'])}</p>
    </div>"""
    return f"""
<section class="report-page">
  <div class="section-head"><div class="section-no">02</div><h2>Como ler a planilha</h2></div>
  <div class="stack">{items}
  </div>
</section>
"""


def render_macroarea(m: dict) -> str:
    dominios = m.get("dominios", [])
    if not dominios:
        dom_html = '<p style="font-size:8.2pt; color:var(--exec-color-ink-muted)">Sem domínio mapeado.</p>'
    else:
        rows = ""
        for d in dominios:
            docs = ", ".join(doc["nome"] for doc in d.get("documentos_principais", [])) or "—"
            rows += f"""
      <div class="dominio-row"><span class="dominio-nome">{e(d['nome'])}</span> <span class="macro-num">({e(d.get('rastreio_id',''))})</span><br>
      <span class="dominio-docs">{e(docs)}</span></div>"""
        dom_html = f'<div class="macro-dominios">{rows}</div>'
    return f"""
  <div class="macro-card">
    <div class="macro-head">
      <h3>{e(m['nome'])}</h3>
      <span class="macro-num">{e(m['rastreio_id'])}</span>
    </div>
    <div class="macro-finalidade">{e(m['finalidade_executiva'])}</div>
    {dom_html}
    <div class="macro-foot">
      <span>{e(m['quantidade_de_campos'])} campos · {e(m['aba_de_preenchimento'])}</span>
      <span>{e(m['situacao'])}</span>
    </div>
  </div>"""


def render_mapa_operacional(mo: dict) -> str:
    macros = mo.get("macroareas", [])
    # 5 per page to keep each page reasonably dense but not overflowing
    pages = []
    chunk = 5
    for i in range(0, len(macros), chunk):
        group = macros[i:i + chunk]
        cards = "".join(render_macroarea(m) for m in group)
        head = f"""<div class="section-head"><div class="section-no">03</div><h2>{e(mo['titulo'])}</h2></div>""" if i == 0 else ""
        lead = f"""<p class="lead">{e(mo['descricao'])}</p>""" if i == 0 else ""
        pages.append(f"""
<section class="report-page">
  {head}
  {lead}
  {cards}
</section>""")
    return "".join(pages)


def render_estrutura(est: dict) -> str:
    def tbl(rows, headers):
        head = "".join(f"<th>{e(h)}</th>" for h in headers)
        body = ""
        for r in rows:
            body += "<tr>" + "".join(f"<td>{e(v)}</td>" for v in r) + "</tr>"
        return f"<table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>"

    visoes = tbl([(v["aba"], v["funcao"]) for v in est.get("visoes_de_leitura", [])], ["Aba", "Função"])
    registros = tbl([(r["aba"], r["funcao"]) for r in est.get("registros_estruturais", [])], ["Aba", "Função"])
    entrada = est.get("entrada_humana", {})
    return f"""
<section class="report-page">
  <div class="section-head"><div class="section-no">04</div><h2>Estrutura da planilha</h2></div>
  <div class="callout" style="margin-bottom:5mm">
    <strong>Entrada humana</strong>
    {e(entrada.get('abas'))} — {e(entrada.get('funcao'))} {e(entrada.get('regra'))}
  </div>
  <div class="grid-2">
    <div>
      <h3 style="font-size:10.5pt">Abas de visão</h3>
      {visoes}
    </div>
    <div>
      <h3 style="font-size:10.5pt">Registros estruturais</h3>
      {registros}
    </div>
  </div>
</section>
"""


def render_pontos_atencao(pontos: list) -> str:
    items = ""
    for p in pontos:
        rastreio = ", ".join(p.get("rastreio", []))
        items += f"""
    <div class="callout">
      <strong>{e(p['titulo'])}</strong>
      {e(p['descricao'])}
      <div style="margin-top:1.5mm"><span class="pill muted">{e(rastreio)}</span></div>
    </div>"""
    return f"""
<section class="report-page">
  <div class="section-head"><div class="section-no">05</div><h2>Pontos de atenção</h2></div>
  <div class="stack">{items}
  </div>
</section>
"""


def render_legenda_e_fonte(legenda: list, fonte: dict) -> str:
    terms = ""
    for t in legenda:
        terms += f"""<div class="term"><dt>{e(t['termo'])}</dt><dd>{e(t['significado'])}</dd></div>"""
    abas = ", ".join(fonte.get("abas_principais_de_rastreio", []))
    return f"""
<section class="report-page">
  <div class="section-head"><div class="section-no">06</div><h2>Legenda executiva</h2></div>
  <dl class="term-grid">{terms}
  </dl>
  <div class="trace-note">
    Fonte: {e(fonte.get('planilha'))} · abas de rastreio: {e(abas)} · {e(fonte.get('regra'))}
  </div>
</section>
"""


def build_html(data: dict) -> str:
    meta = data["meta"]
    body = render_cover(meta, data["visao_geral"])
    body += f"""<span class="report-title-string" style="display:none">{e(meta.get('titulo'))}</span>"""
    body += f"""<span class="report-meta-string" style="display:none">{e(meta.get('fonte_principal'))} · {e(meta.get('data_de_referencia'))}</span>"""
    body += render_visao_geral(data["visao_geral"])
    body += render_como_ler(data["como_ler_a_planilha"])
    body += render_mapa_operacional(data["mapa_operacional"])
    body += render_estrutura(data["estrutura_da_planilha"])
    body += render_pontos_atencao(data["pontos_de_atencao"])
    body += render_legenda_e_fonte(data["legenda_executiva"], data["fonte_e_rastreabilidade"])

    return f"""<!doctype html>
<html lang="pt-BR">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{e(meta.get('titulo'))} — EXECUTAR</title>
<style>{STYLE}</style>
</head>
<body>
{body}
</body>
</html>
"""


def main() -> int:
    if len(sys.argv) != 3:
        print("uso: render_mapa_operacional.py payload.json output.html", file=sys.stderr)
        return 2
    payload_path, out_path = Path(sys.argv[1]), Path(sys.argv[2])
    data = json.loads(payload_path.read_text(encoding="utf-8"))
    try:
        validate(data)
    except ValueError as err:
        print(f"ERRO: {err}", file=sys.stderr)
        return 2
    html = build_html(data)
    out_path.write_text(html, encoding="utf-8")
    print(f"PASS: {out_path}; macroareas={len(data['mapa_operacional']['macroareas'])}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
